export type GuideBlock = { id: string; type: 'text' | 'image' | 'video'; text?: string; url?: string }
export type GuideChapter = { id: string; title: string; body: string; hidden: boolean; blocks: GuideBlock[] }
export type GuideBook = { key: string; title: string; chapters: GuideChapter[] }

function chapter(id: string, title: string, paragraphs: string[]): GuideChapter {
  const blocks = paragraphs.map((text, index) => ({ id: `${id}-${index}`, type: 'text' as const, text }))
  return { id, title, body: paragraphs.join('\n\n'), hidden: false, blocks }
}

